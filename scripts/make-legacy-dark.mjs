// Task 75 · writes the generated part of src/ui2/legacy-dark.css: the dark theme for the old interface's parts that the
// new interface reuses unchanged (Amjd, 2026-11-19: they were light cards on the dark page).
//
// What it does, step by step:
// 1. Finds the reused old components: every file under src/components (and src/plan/developmentPlan.jsx) that a file
//    of src/ui2 imports, and every component those import in turn.
// 2. Collects the class names those components use (the string parts of their className={...} and className="...").
// 3. Reads the old CSS (the files src/main.jsx loads, plus the CSS the components import) and keeps each rule whose
//    selector names one of those classes, outside the old graph's map, which keeps its own look in both themes.
// 4. Maps every FIXED colour in the kept declarations to a dark theme token (public/brand.css names, dark values in
//    src/ui2/theme.css), by what the colour is for: a light surface → --paper, --soft or a tint token by hue (--navy-3,
//    --mist, --warn-bg, --danger-bg); a dark text colour → --ink, --muted, --navy, --teal, --success, --warn or --danger
//    by hue; a light border → --line. Colours that already read on a dark page (dark surfaces with light text, colours
//    given as tokens) are left as they are.
// 5. Writes each kept rule once, under :root[data-scheme="dark"] .ui2-legacy, between the two GENERATED markers of
//    src/ui2/legacy-dark.css. The hand-written rules above the markers stay.
// Run: node scripts/make-legacy-dark.mjs (tests/legacyDark.test.js fails when the file is out of date).
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, normalize } from 'node:path'

const ROOT = process.cwd()
const read = file => readFileSync(join(ROOT, file), 'utf8').replace(/\r\n/g, '\n')
const OUT = 'src/ui2/legacy-dark.css'
const BEGIN = '/* ----- GENERATED by scripts/make-legacy-dark.mjs: do not edit by hand ----- */'
const END = '/* ----- END GENERATED ----- */'
export const PREFIX = ':root[data-scheme="dark"] .ui2-legacy'

// ----- 1. reused components -----
const UI2_FILES = ['src/ui2/AppNext.jsx', 'src/ui2/screens/Profile.jsx', 'src/ui2/screens/Settings.jsx', 'src/ui2/screens/Help.jsx', 'src/ui2/screens/NextSteps.jsx', 'src/ui2/screens/Plan.jsx', 'src/ui2/components/GoalPicker.jsx', 'src/ui2/components/ConnectionsMap.jsx']
const importsOf = file => [...read(file).matchAll(/(?:import\s[^'"]*?from\s*|import\()\s*['"](\.[^'"]+)['"]/g)].map(m => normalize(join(dirname(file), m[1])).replace(/\\/g, '/'))
export function reusedComponents() {
  const seen = new Set()
  const queue = UI2_FILES.flatMap(importsOf).filter(file => /^src\/(components|plan)\/.*\.jsx$/.test(file))
  while (queue.length) {
    const file = queue.shift()
    if (seen.has(file) || !existsSync(join(ROOT, file))) continue
    seen.add(file)
    for (const next of importsOf(file)) if (/^src\/components\/.*\.jsx$/.test(next)) queue.push(next)
  }
  return [...seen].sort()
}

// ----- 2. their class names -----
function classNames(files) {
  const names = new Set(), prefixes = new Set()
  for (const file of files) {
    const source = read(file)
    for (const m of source.matchAll(/className=(?:"([^"]*)"|'([^']*)'|\{)/g)) {
      let text = m[1] ?? m[2]
      if (text === undefined) { // className={...}: the string parts of the expression up to its closing brace
        let depth = 1, i = m.index + m[0].length
        const start = i
        while (i < source.length && depth) { if (source[i] === '{') depth++; else if (source[i] === '}') depth--; i++ }
        text = [...source.slice(start, i - 1).matchAll(/'([^']*)'|"([^"]*)"|`([^`]*)`/g)].map(s => (s[1] ?? s[2] ?? s[3]).replace(/\$\{[^}]*\}/g, '${}')).join(' ')
      }
      for (const token of text.split(/\s+/)) {
        if (/^[a-z][a-z0-9-]*-\$\{\}$/.test(token)) prefixes.add(token.slice(0, -3))
        else if (/^[a-z][a-z0-9_-]*$/.test(token) && token !== '${}') names.add(token)
      }
    }
  }
  return { names, prefixes }
}

// ----- 3. the old CSS rules -----
const OLD_CSS = ['public/brand.css', 'src/cards.css', 'src/styles.css', 'src/experience.css', 'src/digital-interests.css', 'src/knowledge-workspace.css', 'src/relationship-network.css', 'src/semantic-tools.css', 'public/site-layout.css', 'src/redesign.css', 'src/path.css', 'src/pilot.css']
function cssOf(files) {
  const own = files.flatMap(file => [...read(file).matchAll(/import\s+['"](\.[^'"]+\.css)['"]/g)].map(m => normalize(join(dirname(file), m[1])).replace(/\\/g, '/')))
  return [...new Set([...OLD_CSS, ...own])].filter(file => existsSync(join(ROOT, file)))
}
// [{ media, selector, body }] in file order; @media blocks one level deep; @keyframes, @font-face and @supports skipped.
function parseCss(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '')
  const out = []
  let i = 0
  const block = (from) => { let depth = 1, j = from; while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++ } return j }
  const rulesIn = (text, media) => { for (const m of text.matchAll(/([^{}]+)\{([^{}]*)\}/g)) out.push({ media, selector: m[1].trim().replace(/\s+/g, ' '), body: m[2] }) }
  while (i < css.length) {
    const open = css.indexOf('{', i)
    if (open < 0) break
    const head = css.slice(i, open).trim()
    const close = block(open + 1)
    if (head.startsWith('@media')) rulesIn(css.slice(open + 1, close - 1), head.replace(/\s+/g, ' '))
    else if (!head.startsWith('@')) out.push({ media: null, selector: head.replace(/\s+/g, ' '), body: css.slice(open + 1, close - 1) })
    i = close
  }
  return out
}

// The old graph's map keeps its own look (a dark teal map with cream nodes) in both themes; the landing page and the
// old app's frame are never inside the new interface.
const SKIP = /\.relationship-map|\.relationship-node(?![\w-])|\.relationship-(person|interest|goal|evidence|job|training|peer|project)(?![\w-])|\.relation-|\.arrow-|k-network|landing|\.app-(shell|sidebar|topbar|main|overlay|brand|lang)|bottom-nav|site-|k-site|\.hero|quick-tour/

// ----- 4. colours -----
const NAMED = { white: '#ffffff', black: '#000000' }
export function parseColour(text) {
  const named = NAMED[text.toLowerCase()]
  if (named) text = named
  let m = text.match(/^#([0-9a-f]{3,8})$/i)
  if (m) {
    let h = m[1]
    if (h.length === 3 || h.length === 4) h = [...h].map(c => c + c).join('')
    const a = h.length === 8 ? parseInt(h.slice(6), 16) / 255 : 1
    return { rgb: [0, 2, 4].map(k => parseInt(h.slice(k, k + 2), 16)), a }
  }
  m = text.match(/^rgba?\(([^)]+)\)$/i)
  if (m) {
    const parts = m[1].split(/[\s,/]+/).filter(Boolean)
    const a = parts[3] === undefined ? 1 : parts[3].endsWith('%') ? parseFloat(parts[3]) / 100 : parseFloat(parts[3])
    return { rgb: parts.slice(0, 3).map(Number), a }
  }
  return null
}
const lum = ([r, g, b]) => { const f = v => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4 }; return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b) }
function hsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min
  if (!d) return { h: 0, s: 0, l }
  const s = d / (1 - Math.abs(2 * l - 1))
  const h = max === r ? 60 * (((g - b) / d) % 6) : max === g ? 60 * ((b - r) / d + 2) : 60 * ((r - g) / d + 4)
  return { h: (h + 360) % 360, s, l }
}
const hue = h => (h < 20 || h >= 330 ? 'red' : h < 70 ? 'yellow' : h < 150 ? 'green' : h < 190 ? 'teal' : h < 260 ? 'blue' : 'purple')
// A light surface → the dark surface token for its kind.
export function surfaceToken(rgb) {
  const { h, s } = hsl(rgb), L = lum(rgb)
  if (s < 0.12 || L > 0.96) return L > 0.9 ? 'paper' : 'soft'
  return { red: 'danger-bg', yellow: 'warn-bg', green: 'mist', teal: 'mist', blue: s > 0.25 && L < 0.92 ? 'navy-3' : 'soft', purple: 'navy-3' }[hue(h)]
}
// A dark text colour → the dark theme's text token for its kind.
export function textToken(rgb) {
  const { h, s } = hsl(rgb), L = lum(rgb)
  if (s < 0.15) return L < 0.04 ? 'ink' : 'muted'
  const kind = hue(h)
  if (kind === 'blue') return s < 0.45 ? (L < 0.05 ? 'ink' : 'muted') : 'navy'
  return { red: 'danger', yellow: 'warn', green: 'success', teal: 'teal', purple: 'ink' }[kind]
}
// A border colour → --line when light, else the text token of its kind (a coloured edge keeps its meaning; a neutral or
// purple edge is --muted, the new interface's control edge, never the text colour).
export const borderToken = rgb => { if (lum(rgb) > 0.4) return 'line'; const token = textToken(rgb); return token === 'ink' ? 'muted' : token }

const COLOUR = /#[0-9a-f]{3,8}\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b/gi
const colours = value => (value.match(COLOUR) || []).map(text => ({ text, ...parseColour(text) })).filter(c => c.rgb)
const declarations = body => body.split(';').map(part => part.trim()).filter(Boolean).map(part => {
  const at = part.indexOf(':')
  const important = /!important\s*$/.test(part)
  return { prop: part.slice(0, at).trim().toLowerCase(), value: part.slice(at + 1).replace(/!important\s*$/, '').trim(), important }
})

// The dark declarations for one old rule ([] when nothing in it needs changing). `selected`: the rule styles a pressed or
// selected control (its old fill is dark, so it stays dark by itself, but the rule for the same control without the state
// is repainted under the prefix and would win): it takes the dark theme's selected look, the new interface's own (a --navy
// fill with --paper words, as button.ui2-chip[aria-pressed="true"]).
export function darkDeclarations(body, selected = false) {
  const decl = declarations(body)
  const out = []
  const bg = decl.find(d => d.prop === 'background' || d.prop === 'background-color')
  const bgColours = bg && !/url\(/.test(bg.value) ? colours(bg.value).filter(c => c.a > 0.3) : []
  const darkBg = bgColours.length > 0 && bgColours.every(c => lum(c.rgb) < 0.2)
  const midBg = !darkBg && bgColours.some(c => lum(c.rgb) >= 0.2)
  const set = (prop, token, important) => out.push(`${prop}:var(--${token})${important ? '!important' : ''}`)
  if (darkBg && selected) return [`${bg.prop === 'background' ? 'background' : 'background-color'}:var(--navy)`, 'border-color:var(--navy)', 'color:var(--paper)']
  if (midBg) {
    const lightest = bgColours.reduce((a, b) => (lum(b.rgb) > lum(a.rgb) ? b : a))
    set(bg.prop === 'background' ? 'background' : 'background-color', lum(lightest.rgb) > 0.6 ? surfaceToken(lightest.rgb) : 'navy-3', bg.important)
  }
  for (const d of decl) {
    if (d.prop === 'color' && !darkBg) {
      const c = colours(d.value)[0]
      if (c && lum(c.rgb) < 0.2) set('color', textToken(c.rgb), d.important)
    } else if (/^border(-(top|right|bottom|left|block|inline)(-(start|end))?)?(-color)?$/.test(d.prop) || d.prop === 'outline-color') {
      const c = colours(d.value)[0]
      // A light edge is always --line; a dark edge around a dark surface stays as it is.
      if (c && (!darkBg || lum(c.rgb) > 0.4)) {
        const side = d.prop.replace(/-color$/, '')
        set(d.prop === 'outline-color' ? 'outline-color' : `${side}-color`, borderToken(c.rgb), d.important)
      }
    } else if (d.prop === 'fill') {
      const c = colours(d.value)[0]
      if (c && lum(c.rgb) < 0.2) set('fill', textToken(c.rgb), d.important)
      else if (c && lum(c.rgb) > 0.6) set('fill', surfaceToken(c.rgb), d.important)
    } else if (d.prop.startsWith('--')) {
      const c = colours(d.value)
      if (c.length === 1 && c[0].text === d.value && lum(c[0].rgb) > 0.6) out.push(`${d.prop}:var(--${surfaceToken(c[0].rgb)})`)
    }
  }
  return out
}

// "[dir=rtl] .x" and "html[lang=en] .x" name the page, which is outside .ui2-legacy: they move onto :root.
export function prefixed(selector) {
  return selector.split(',').map(part => part.trim()).map(part => {
    const lead = part.match(/^((?:html)?(?:\[(?:dir|lang)=?[^\]]*\])+)\s+(.*)$/)
    return lead ? `:root[data-scheme="dark"]${lead[1].replace(/^html/, '')} .ui2-legacy ${lead[2]}` : `${PREFIX} ${part}`
  }).join(',')
}

export function generate() {
  const files = reusedComponents()
  // The new interface's own files also put old classes inside .ui2-legacy (Settings' "deleted" confirmation).
  const { names, prefixes } = classNames([...files, ...UI2_FILES])
  const uses = selector => (selector.match(/\.[a-zA-Z][\w-]*/g) || []).some(cls => names.has(cls.slice(1)) || [...prefixes].some(p => cls.slice(1).startsWith(p)))
  const lines = []
  let media = null
  const seen = new Set()
  for (const file of cssOf(files)) {
    for (const rule of parseCss(read(file))) {
      if (/^(:root|html|body|\*)$/.test(rule.selector) || !uses(rule.selector)) continue
      const parts = rule.selector.split(',').map(p => p.trim()).filter(p => uses(p) && !SKIP.test(p))
      const dark = darkDeclarations(rule.body, parts.every(part => /\[aria-(pressed|selected)="?true"?\]/.test(part)))
      if (!parts.length || !dark.length) continue
      const line = `${prefixed(parts.join(','))}{${dark.join(';')}}`
      if (seen.has(`${rule.media}|${line}`)) continue
      seen.add(`${rule.media}|${line}`)
      if (rule.media !== media) { if (media) lines.push('}'); if (rule.media) lines.push(`${rule.media}{`); media = rule.media }
      lines.push(rule.media ? ` ${line}` : line)
    }
  }
  if (media) lines.push('}')
  return { files, css: lines.join('\n') }
}

export function render(current) {
  const { files, css } = generate()
  const note = `/* From the old CSS of: ${files.map(f => f.replace(/^src\/(components\/)?/, '')).join(', ')}. */`
  const generated = `${BEGIN}\n${note}\n${css}\n${END}\n`
  const at = current.indexOf(BEGIN)
  return (at < 0 ? `${current.trimEnd()}\n\n` : current.slice(0, at)) + generated
}

if (process.argv[1] && normalize(process.argv[1]).endsWith(normalize('scripts/make-legacy-dark.mjs'))) {
  const next = render(read(OUT))
  writeFileSync(join(ROOT, OUT), next)
  console.log(`${OUT}: ${next.split('\n').length} lines`)
}
